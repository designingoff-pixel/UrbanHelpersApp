// ─────────────────────────────────────────────────────────────────────────────
// Seeder Execution
// ─────────────────────────────────────────────────────────────────────────────
async function run() {
  const args = process.argv.slice(2);
  const isDryRun = args.includes("--dry-run");
  const onlyProducts = args.includes("--products");
  const onlyServices = args.includes("--services");

  const shouldSeedProducts = !onlyServices;
  const shouldSeedServices = !onlyProducts;

  console.log("==================================================================");
  console.log(" Urban Helpers — Customer Store Inventory & Services Seeder");
  console.log("==================================================================");
  console.log(`Mode: ${isDryRun ? "DRY RUN (No writes)" : "LIVE FIRESTORE SEED"}`);
  console.log(`Target Collections: ${shouldSeedProducts ? "shop_products " : ""}${shouldSeedServices ? "serviceCategories" : ""}\n`);

  if (isDryRun) {
    if (shouldSeedProducts) {
      console.log(`📦 [shop_products] Total Products: ${SHOP_PRODUCTS.length}`);
      const catCount = {};
      SHOP_PRODUCTS.forEach((p) => { catCount[p.category] = (catCount[p.category] || 0) + 1; });
      console.log("   Breakdown by Category:", catCount);
    }
    if (shouldSeedServices) {
      console.log(`\n🛠️  [serviceCategories] Total Categories: ${SERVICE_CATEGORIES.length}`);
      let totalSubs = 0;
      SERVICE_CATEGORIES.forEach((c) => {
        totalSubs += c.subServices.length;
        console.log(`   - ${c.name} (${c.id}): ${c.subServices.length} sub-services`);
      });
      console.log(`   Total Sub-Services across all categories: ${totalSubs}`);
    }
    console.log("\nDry run completed successfully. No changes were made.");
    process.exit(0);
  }

  const app = initializeApp(firebaseConfig);
  const db = getFirestore(app);

  try {
    if (shouldSeedProducts) {
      console.log(`⏳ Seeding ${SHOP_PRODUCTS.length} shop products to 'shop_products'...`);
      let pCount = 0;
      for (const prod of SHOP_PRODUCTS) {
        await setDoc(
          doc(db, "shop_products", prod.id),
          {
            ...prod,
            createdAt: serverTimestamp(),
            updatedAt: serverTimestamp(),
          },
          { merge: true }
        );
        pCount++;
        process.stdout.write(`   [${pCount}/${SHOP_PRODUCTS.length}] Synced product: ${prod.name}\n`);
      }
      console.log(`✅ Successfully seeded ${pCount} shop products to Firestore!\n`);
    }

    if (shouldSeedServices) {
      console.log(`⏳ Seeding ${SERVICE_CATEGORIES.length} service categories to 'serviceCategories'...`);
      let sCount = 0;
      for (const cat of SERVICE_CATEGORIES) {
        await setDoc(
          doc(db, "serviceCategories", cat.id),
          {
            id: cat.id,
            name: cat.name,
            icon: cat.icon,
            order: cat.order,
            gradient: cat.gradient,
            accent: cat.accent,
            tagline: cat.tagline,
            imageUrl: cat.imageUrl,
            subServices: cat.subServices,
            updatedAt: serverTimestamp(),
          },
          { merge: true }
        );
        sCount++;
        process.stdout.write(`   [${sCount}/${SERVICE_CATEGORIES.length}] Synced category: ${cat.name} (${cat.subServices.length} services)\n`);
      }
      console.log(`✅ Successfully seeded ${sCount} service categories to Firestore!\n`);
    }

    console.log("==================================================================");
    console.log(" ✨ Inventory setup complete! All items ready for checkout.");
    console.log("==================================================================");
    process.exit(0);
  } catch (err) {
    console.error("❌ Seeding failed:", err.message);
    process.exit(1);
  }
}

run();
